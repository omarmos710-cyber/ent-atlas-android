#!/usr/bin/env python3
"""Write web/sw.js, the offline service worker of the web app, from the files that are actually in the app.

Why it is built this way (the slow-update problem):
  The old worker renamed its whole cache on every release and downloaded every code and data file again
  (about 70 MB: the search index, the search model, every article), even the ones that had not changed, one
  batch after another. Each update therefore took minutes on a phone. The operative figures (fig2/m, 65 MB)
  were not in the offline list at all, so they loaded one by one as they were opened, or only after
  "Save them all" in the Logbook.

Now every file is listed with a fingerprint of its content (the first 12 hex digits of its SHA-256):
  * one cache that is never renamed holds "path?v=fingerprint", so a release downloads only the files whose
    content changed; everything else is already there;
  * the code and data are fetched before the new version takes over (a few files, so seconds), eight at a time;
  * figures, scans and PDFs, the operative figures included, are filled in the background after the app opens
    (the page asks the worker), most-used first, and resume where they stopped if the phone sleeps;
  * on the first run of this scheme, copies already saved by the old worker are reused when their fingerprint
    matches, so nothing that is already on the phone is downloaded again.
Run: python3 tools/build_sw.py (build_articles.py runs it last; CI checks it is up to date).
"""
import hashlib, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WWW = os.path.join(ROOT, 'app', 'src', 'main', 'assets', 'www')
WEB = os.path.join(ROOT, 'web')
OUT = os.path.join(WEB, 'sw.js')
SKIP = {'search/rr/LICENSE.txt'}
MEDIA_EXT = ('.jpg', '.jpeg', '.png', '.webp', '.gif', '.svg', '.pdf')


def fp(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()[:12]


def is_media(p):
    # the smart-search reranker (34 MB) only polishes the order of an answer that search already shows, so it is
    # saved with the media, first in line, instead of delaying the first install
    return p.lower().endswith(MEDIA_EXT) or p.startswith('im/') or p.startswith('search/rr/')


def media_rank(p):
    """Background order: what is opened most, and is smallest, first."""
    for k, pre in enumerate(('search/rr/', 'fig2/t/', 'theatre/basics/img/', 'clinic/fig/', 'fig2/m/', 'fig2/', 'im/', 'icons/', 'pdf/')):
        if p.startswith(pre):
            return k
    return 10


def files():
    out = {}
    for d, _, fs in os.walk(WWW):
        for f in fs:
            full = os.path.join(d, f)
            rel = os.path.relpath(full, WWW).replace(os.sep, '/')
            if rel in SKIP or f.startswith('.'):
                continue
            out[rel] = full
    # the web shell (manifest and icons) lives in web/ and is served beside the app
    for d, _, fs in os.walk(WEB):
        for f in fs:
            full = os.path.join(d, f)
            rel = os.path.relpath(full, WEB).replace(os.sep, '/')
            if rel in ('sw.js', '_headers') or f.startswith('.'):
                continue
            out[rel] = full
    return out


TEMPLATE = r'''/* The ENT Companion, offline worker. GENERATED by tools/build_sw.py: do not edit by hand.
   One cache that is never renamed holds every file as "path?v=fingerprint". A new release downloads only the
   files whose content changed (the code first, before it takes over; figures, scans and PDFs in the background
   afterwards), so an update takes seconds and every figure, the operative figures included, is kept offline. */
const BUILD="@@BUILD@@";
const STORE="ent-atlas-store";
const P=@@PATHS@@;
const R=@@REVS@@;
const NCORE=@@NCORE@@; /* P[0..NCORE) is code and data; the rest is media, most-used first */
const IX=new Map(P.map((p,i)=>[p,i]));
const SCOPE=new URL(self.registration.scope).pathname;
const K=i=>P[i]+"?v="+R[i];
const rel=u=>{const x=new URL(u,self.registration.scope);let p=x.pathname.startsWith(SCOPE)?x.pathname.slice(SCOPE.length):x.pathname.replace(/^\//,"");return decodeURIComponent(p)||"index.html"};
const keyOf=r=>{const x=new URL(r.url);return rel(r.url)+x.search};
/* the host answers index.html with a redirect to "/"; a browser will not open a page from a redirected copy, so it is
   re-wrapped as a plain response (this is what lets the app open offline) */
const plain=r=>r&&r.redirected?new Response(r.body,{status:r.status,statusText:r.statusText,headers:r.headers}):r;
const LEGACY=n=>n.startsWith("ent-atlas-")&&n!==STORE&&n!=="ent-atlas-ext";
async function hex(buf){const d=new Uint8Array(await crypto.subtle.digest("SHA-256",buf));let s="";for(let k=0;k<6;k++)s+=d[k].toString(16).padStart(2,"0");return s}
/* a copy the old worker already saved is reused when its content is the same */
async function fromLegacy(st,i,names){for(const n of names){const c=await caches.open(n);const hit=await c.match(P[i],{ignoreSearch:true});if(!hit||!hit.ok)continue;
  try{const buf=await hit.clone().arrayBuffer();if(await hex(buf)===R[i]){await st.put(K(i),new Response(buf,{headers:hit.headers}));return true}}catch(e){}}return false}
/* a download is kept only if its content matches this version's fingerprint, so a file from a newer or older
   deploy is never saved under the wrong version (a failed install keeps the working version) */
async function fromNet(st,i,tries){for(let t=0;t<(tries||3);t++){try{const r=await fetch(new Request(K(i),{cache:"no-cache"}));
  if(r.ok){const buf=await r.arrayBuffer();if(await hex(buf)!==R[i])return false;await st.put(K(i),new Response(buf,{status:200,headers:r.headers}));return true}}catch(e){}}return false}
async function pool(list,n,fn){let j=0;const run=async()=>{while(j<list.length){const i=list[j++];await fn(i)}};await Promise.all(Array.from({length:n},run))}
async function missing(st,from,to){const have=new Set((await st.keys()).map(keyOf));const out=[];for(let i=from;i<to;i++)if(!have.has(K(i)))out.push(i);return out}
self.addEventListener("install",e=>{e.waitUntil((async()=>{const st=await caches.open(STORE);const names=(await caches.keys()).filter(LEGACY);
  const need=await missing(st,0,NCORE);let failed=0;
  await pool(need,8,async i=>{if(await fromLegacy(st,i,names))return;if(!(await fromNet(st,i,3)))failed++});
  if(failed)throw new Error(failed+" files could not be downloaded"); /* keep the working version; the next check tries again */
  await self.skipWaiting()})())});
self.addEventListener("activate",e=>{e.waitUntil((async()=>{
  /* the old code caches go; the old media caches stay until their figures have been moved across (fill) */
  for(const n of await caches.keys())if((LEGACY(n)&&n!=="ent-atlas-media")||n==="ent-atlas-ext")await caches.delete(n);
  const st=await caches.open(STORE),want=new Set(P.map((p,i)=>K(i)));
  for(const r of await st.keys())if(!want.has(keyOf(r)))await st.delete(r);
  await self.clients.claim()})())});
/* figures, scans and PDFs: filled in the background when the page asks, resumed on the next visit if stopped */
let FILLING=null;
function fill(){if(FILLING)return FILLING;FILLING=(async()=>{const st=await caches.open(STORE);const need=await missing(st,NCORE,P.length);if(!need.length)return;
  const names=(await caches.keys()).filter(n=>n==="ent-atlas-media");let done=0,got=0;
  const tell=async m=>{for(const c of await self.clients.matchAll())c.postMessage(m)};
  await pool(need,6,async i=>{if(await fromLegacy(st,i,names)||await fromNet(st,i,2))got++;if(++done%100===0)tell({fill:[done,need.length]})});
  const left=(await missing(st,NCORE,P.length)).length;
  if(!left)await caches.delete("ent-atlas-media");
  tell({fill:[done,need.length],left});if(got&&!left)tell("cached")})().finally(()=>{FILLING=null});return FILLING}
/* how much is still to save: the page shows it in More */
async function status(){const st=await caches.open(STORE);return (await missing(st,NCORE,P.length)).length}
self.addEventListener("message",e=>{if(e.data==="fill")e.waitUntil(fill());
  else if(e.data==="status"&&e.source)e.waitUntil(status().then(n=>e.source.postMessage({missing:n,total:P.length-NCORE})))});
self.addEventListener("fetch",e=>{const req=e.request;if(req.method!=="GET")return;const url=new URL(req.url);
  if(url.origin!==location.origin)return;
  /* only the app itself is "the page"; other .html files (summary boards, mind maps, opened inside the app as
   frames) are ordinary files and are looked up in the file list */
  const page=req.mode==="navigate"&&(r0=>r0==="index.html"||!/[./]/.test(r0))(rel(req.url));
  e.respondWith((async()=>{const st=await caches.open(STORE);
    /* the page comes from this version's saved copy, so it always matches the scripts saved with it; a newer
       version is picked up by the update check, which installs it whole and then reloads */
    if(page){const i=IX.get("index.html");const hit=plain(i!==undefined&&await st.match(K(i)));if(hit)return hit;
      try{const r=await fetch(req);if(r.ok||r.type==="opaqueredirect")return r}catch(err){}
      return plain(await caches.match(req,{ignoreSearch:true}))||Response.error()}
    const i=IX.get(rel(req.url));
    /* copies saved by older versions may be redirected responses (the host redirects x.html to x); unwrap them */
    if(i!==undefined){const hit=plain(await st.match(K(i)));if(hit)return hit}
    const old=await caches.match(req,{ignoreSearch:true});if(old)return old;
    try{const r=await fetch(req);if(!(r.ok&&i!==undefined&&!url.search))return r;
      const buf=await r.arrayBuffer();if(await hex(buf)===R[i])st.put(K(i),new Response(buf,{status:200,headers:r.headers})).catch(()=>{});
      return new Response(buf,{status:r.status,statusText:r.statusText,headers:r.headers})}catch(err){return Response.error()}})())});
'''


def main(check=False):
    fs = files()
    core = sorted(p for p in fs if not is_media(p))
    media = sorted((p for p in fs if is_media(p)), key=lambda p: (media_rank(p), p))
    order = core + media
    revs = [fp(fs[p]) for p in order]
    build = hashlib.sha256(''.join(revs).encode()).hexdigest()[:10]
    js = (TEMPLATE.replace('@@BUILD@@', build).replace('@@PATHS@@', json.dumps(order, ensure_ascii=False, separators=(',', ':')))
          .replace('@@REVS@@', json.dumps(revs, separators=(',', ':'))).replace('@@NCORE@@', str(len(core))))
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if check:
        if old != js:
            print('web/sw.js is out of date: run python3 tools/build_sw.py')
            return 1
        print('web/sw.js is up to date (%d files)' % len(order))
        return 0
    if old != js:
        open(OUT, 'w', encoding='utf-8').write(js)
    size = lambda ps: sum(os.path.getsize(fs[p]) for p in ps) / 1e6
    print('sw.js: %d code and data files (%.1f MB), %d media files (%.1f MB), build %s, %d KB'
          % (len(core), size(core), len(media), size(media), build, len(js) // 1024))
    return 0


if __name__ == '__main__':
    sys.exit(main(check='--check' in sys.argv))

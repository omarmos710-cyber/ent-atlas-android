def main():
    s = open(IDX, encoding='utf-8').read()
    i = s.index('const CONDS='); j = s.index('\n', i)
    raw = s[i + len('const CONDS='):j].rstrip().rstrip(';')
    C = json.loads(raw); ids = {c['id'] for c in C}
    miss = [k for k in CORE if k not in ids]
    if miss: raise SystemExit('unknown ids: %s' % miss)
    for c in C:
        c['les'] = LES_OVR.get(c['id']) or RLES.get(c['r'], '')
        c.pop('core', None); c.pop('kf', None)
        if c['id'] in CORE:
            pg, see, dd, chk = CORE[c['id']]
            c['core'] = 1
            c['kf'] = {'see': see, 'dd': dd, 'chk': chk, 'pg': pg - DI_OFF if pg else 0}
    out = 'const CONDS=' + json.dumps(C, ensure_ascii=False, separators=(',', ':')) + ';'
    s = s[:i] + out + s[j:]
    open(IDX, 'w', encoding='utf-8').write(s)
    print('core', sum(1 for c in C if c.get('core')), 'of', len(C))

if __name__ == '__main__':
    main()
